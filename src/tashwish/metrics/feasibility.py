"""How coarse must the grid be? Share of cell-buckets that reach the minimum number of eligible aircraft.

Reproducible from ingested points; the table in docs/DATA_QUALITY.md is generated by this module, not typed.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from .. import config as cfg
from ..ingest.pipeline import read_manifest
from .aggregate import add_cells, aircraft_buckets, metric_samples
from .loader import load_points

GRIDS = [cfg.Grid(r, h) for r in (3, 4, 5) for h in (1, 3, 6, 24)]


def feasibility(points: pd.DataFrame, grids=GRIDS) -> pd.DataFrame:
    s = metric_samples(points)
    s = s[s["alt_baro_ft"] >= cfg.ENROUTE_MIN_FT]
    rows = []
    for g in grids:
        ab = aircraft_buckets(add_cells(s, g))
        ab = ab[(ab.stratum == "enroute") & (ab.n_samples >= cfg.MIN_SAMPLES_PER_AIRCRAFT)]
        n = ab.groupby(["cell", "bucket"]).icao24.nunique()
        rows.append(
            {
                "h3_res": g.h3_res,
                "bucket_h": g.bucket_hours,
                "cell_buckets": int(len(n)),
                "share_ge_5": round(float((n >= 5).mean()), 3) if len(n) else float("nan"),
                "share_ge_10": round(float((n >= 10).mean()), 3) if len(n) else float("nan"),
                "median_aircraft": float(n.median()) if len(n) else float("nan"),
                "testable_cell_buckets": int((n >= cfg.MIN_AIRCRAFT_PER_CELL).sum()),
            }
        )
    return pd.DataFrame(rows)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--interim", type=Path, default=Path("data/interim"))
    ap.add_argument("--out", type=Path, default=Path("docs/tables/grid_feasibility.md"))
    a = ap.parse_args()
    days = sorted(r["day"] for r in read_manifest(a.interim / "manifest.jsonl") if r["status"] == "complete")
    pts = load_points(a.interim, days)
    df = feasibility(pts)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(
        f"<!-- generated by python -m tashwish.metrics.feasibility; days: {days[0]}..{days[-1]} ({len(days)} days) -->\n"
        + df.to_markdown(index=False)
        + "\n"
    )
    print(df.to_string(index=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
