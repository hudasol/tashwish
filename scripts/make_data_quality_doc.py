"""Generate docs/DATA_QUALITY.md from the manifest and per-day quality reports. Every number comes from the data."""

from __future__ import annotations

import json
import sys
from pathlib import Path

import duckdb
import pandas as pd

from tashwish.ingest.pipeline import read_manifest
from tashwish.split import split

interim = Path(sys.argv[1] if len(sys.argv) > 1 else "data/interim")
out = Path(sys.argv[2] if len(sys.argv) > 2 else "docs/DATA_QUALITY.md")
man = [r for r in read_manifest(interim / "manifest.jsonl") if r["status"] == "complete"]
latest = {r["day"]: r for r in man}
# Development days only: a held out day is never listed here and its quality file and points are never opened.
held_out = {d.isoformat() for d in split()[1]}
days = sorted(d for d in latest if d not in held_out)
assert not held_out.intersection(days)
reports = {d: json.loads((interim / "quality" / f"{d}.json").read_text(encoding="utf-8")) for d in days}

rows = []
for d in days:
    q, m = reports[d], latest[d]
    mp = q.get("metric_population", {})
    rows.append(
        {
            "day": d,
            "release": m["release_kind"],
            "archive_MiB": round(sum(p["bytes"] for p in m["parts"]) / 2**20),
            "trace_files": q["parse_stats"].get("trace_files"),
            "gulf_aircraft": q.get("aircraft"),
            "airborne_aircraft": mp.get("aircraft"),
            "airborne_rows": mp.get("rows"),
            "vehicle_rows_excluded": mp.get("excluded_non_transponder_rows"),
            "quality_present": q.get("share_rows_with_quality"),
            "own_quality": q.get("share_rows_carrying_own_quality"),
            "nic_lt4": q.get("share_nic_below_4"),
            "nacp_lt5": q.get("share_nac_p_below_5"),
            "nacp_lt8": q.get("share_nac_p_below_8"),
            "min_hourly_aircraft": min(q["hourly_aircraft"]) if q.get("hourly_aircraft") else None,
        }
    )
t = pd.DataFrame(rows)
fields = pd.DataFrame({d: reports[d].get("field_presence_rate", {}) for d in days}).T
feas = Path("docs/tables/grid_feasibility.md")

files = ", ".join(f"'{interim / f'points_{d}.parquet'}'" for d in days)
con = duckdb.connect()
con.execute(f"create view p as select icao24, ts, src_type, on_ground, nic, q_carried from read_parquet([{files}])")
gap = con.sql("""
with own as (select icao24, ts, lag(ts) over (partition by icao24 order by ts) prev
             from p where not q_carried and nic is not null and not on_ground and src_type <> 'adsb_icao_nt')
select quantile_cont(epoch(ts) - epoch(prev), [0.5, 0.95, 0.99]) from own where prev is not null
""").fetchone()[0]
dup = con.sql("""
with d as (select icao24, ts, any_value(src_type) s, any_value(on_ground) g, count(*) c from p group by 1, 2 having count(*) > 1)
select count(*) total_keys, sum(case when s = 'adsb_icao_nt' and g then 1 else 0 end) vehicle_keys from d
""").fetchone()

L = []
L.append("# Data quality report\n")
L.append(
    "Generated by `scripts/make_data_quality_doc.py` from `data/interim/manifest.jsonl` and `data/interim/quality/*.json` (development days only)."
)
L.append(
    "Every number below is computed by this script from the ingested development days. Held out days are not read. Re run it after ingesting more days.\n"
)
L.append(f"- Development days ingested: **{len(days)}** ({days[0]} to {days[-1]})" if days else "- No days ingested")
L.append("- Source: adsb.lol `globe_history` (ODbL 1.0), Gulf box lat 22 to 31 N, lon 46 to 62 E")
L.append(f"- Code versions seen: {sorted({r['code_version'] for r in latest.values()})}\n")
L.append("## Definitions used in this report\n")
L.append(
    "- **Gulf aircraft:** unique ICAO24 with at least one trace point in the box that day (includes ground vehicles)."
)
L.append("- **Airborne (metric population):** not a non transponder emitter (`adsb_icao_nt`), not on the ground.")
L.append(
    "- **Quality present:** share of airborne rows with a NIC value, after carrying the most recent aircraft object forward at most 120 s."
)
L.append(
    "- **Own quality:** share of airborne rows whose own trace point carried the aircraft object (the rest are carried forward)."
)
L.append(
    "- **NIC<4 / NACp<5 / NACp<8:** share of airborne rows with quality, per row (not per aircraft). These are descriptive row shares, not the detection statistic.\n"
)
L.append("## Per day summary\n")
L.append(t.to_markdown(index=False))
L.append("\n## Field presence among airborne rows (share non null)\n")
L.append(fields.round(3).to_markdown())
L.append("\n## Findings that shaped the design (each is reproducible from the tables above and the code)\n")
L.append(
    f"1. **Ground vehicle rows are a large part of the raw point count.** Rows from `adsb_icao_nt` (non transponder emitters such as airport vehicles per the readsb documentation) are all on the ground and are excluded from aircraft metrics. Their count is in the `vehicle_rows_excluded` column against `airborne_rows`; they outnumber the airborne rows on {int((t['vehicle_rows_excluded'] > t['airborne_rows']).sum())} of {len(t)} days."
)
L.append(
    f"2. **Quality is carried by a minority of points.** `own_quality` is well below `quality_present`; the carry forward rule (120 s) recovers the rest. Over all development days, the gap between consecutive own quality rows of an aircraft has median {gap[0]:.1f} s, 95th percentile {gap[1]:.1f} s and 99th percentile {gap[2]:.1f} s."
)
L.append(
    f"3. **Coverage is thin.** The number of airborne Gulf aircraft per day (column `airborne_aircraft`) ranges from {int(t['airborne_aircraft'].min())} to {int(t['airborne_aircraft'].max())}, and `min_hourly_aircraft` (lowest {int(t['min_hourly_aircraft'].min())}) shows how few are visible in the quietest hour. This is a property of the volunteer receiver network, not of air traffic itself, and is why the coverage model gates every claim."
)
L.append(
    f"4. **Duplicate (icao24, ts) keys** occur almost only for ground vehicles: {dup[1]} of {dup[0]} duplicate keys over all development days are `adsb_icao_nt` on the ground. They are excluded with the vehicles.\n"
)
L.append("## Grid feasibility (why H3 resolution 4 with 3 hour buckets)\n")
if feas.exists():
    L.append(feas.read_text(encoding="utf-8"))
else:
    L.append("_Run `python -m tashwish.metrics.feasibility` to generate._")
L.append(
    "\n`share_ge_5` is the share of cell-buckets with at least 5 eligible aircraft (en-route, at least 2 quality samples each). It decides how much of the map can be tested at all.\n"
)
out.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
print("wrote", out)
