"""Generate the status block of README.md from result files.

  python scripts/make_readme_status.py           # rewrite the block between the STATUS markers in README.md
  python scripts/make_readme_status.py --check   # exit 1 if README.md differs from the generated block

Every number in the block is read from results/headline.json, results/regimes.csv, results/predictions_scored.json,
results/FREEZE.json and release/manifest.json. Nothing is typed by hand. The block avoids hyphenated words.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
BEGIN = "<!-- STATUS:BEGIN -->"
END = "<!-- STATUS:END -->"

MEASURES = [
    ("jamming_recall_easy", "Injected jamming like, easy tier, recall"),
    ("jamming_recall_medium", "Injected jamming like, medium tier, recall"),
    ("jamming_recall_hard", "Injected jamming like, hard tier, recall"),
    ("spoofing_recall_3plus_aircraft", "Injected spoofing like, 3 or more aircraft, recall"),
    ("false_coverage_rate", "Covered cells with too few aircraft (false coverage)"),
]
CLASS_LABEL = {"synthetic": "SYNTHETIC", "observed": "OBSERVED"}


def _fmt(r: dict | None) -> str:
    if r is None:
        return "n/a"
    return f"{r['value']:.3f} ({r['ci_lo']:.3f} to {r['ci_hi']:.3f}; n {r['n']}, {r['n_days']} days)"


def _load(rel: str):
    return json.loads((ROOT / rel).read_text(encoding="utf-8"))


def build_block() -> str:
    head = _load("results/headline.json")
    scored = _load("results/predictions_scored.json")
    freeze = _load("results/FREEZE.json")
    manifest = _load("release/manifest.json")
    reg = pd.read_csv(ROOT / "results/regimes.csv")

    sys.path.insert(0, str(ROOT / "src"))
    from tashwish.split import RULE_ID

    win = manifest["study_window"]
    n_days = len(manifest["days"])
    n_dev, n_held = len(freeze["dev_days"]), len(freeze["held_out_days"])

    by = {(r["metric"], r["regime"]): r for r in head["results"]}
    cls = {r["metric"]: r["data_class"] for r in head["results"]}
    rows = []
    for key, label in MEASURES:
        pooled = by.get((key, "pooled"))
        normal = by.get((key + "_normal", "traffic_normal"))
        reduced = by.get((key + "_reduced", "traffic_reduced"))
        rows.append(f"| {label} | {CLASS_LABEL[cls[key]]} | {_fmt(pooled)} | {_fmt(normal)} | {_fmt(reduced)} |")

    ev = [r for r in scored if r.get("scored")]
    hits = sum(1 for r in ev if r["hit"] is True)
    misses = sum(1 for r in ev if r["hit"] is False)
    notev = sum(1 for r in ev if r["hit"] is None)
    miss_ids = ", ".join(r["id"] for r in ev if r["hit"] is False)

    reg = reg.sort_values("day")
    first_red = reg[reg["traffic"] == "reduced"]["day"].iloc[0]
    first_elev = reg[reg["degraded"] == "elevated"]["day"].iloc[0]
    before = reg[reg["day"] < first_red]
    after = reg[reg["day"] >= first_elev]
    n_red = int((reg["traffic"] == "reduced").sum())
    held = reg[reg["split"] == "held_out"]
    n_held_red = int((held["traffic"] == "reduced").sum())
    n_held_norm = int((held["traffic"] == "normal").sum())

    lines = [
        BEGIN,
        "<!-- Generated by scripts/make_readme_status.py from result files. Do not edit by hand. -->",
        "",
        "**What this repository shows (study snapshot, not a live feed)**",
        "",
        f"- Study window: {win['start']} to {win['end']}, {n_days} UTC days of public ADS-B, released as a release candidate "
        f"(dataset version `{manifest['dataset_version']}`, built at code commit `{manifest['code_commit']}`).",
        f"- Split rule `{RULE_ID}`: {n_dev} development days and {n_held} held out days. The held out days were fixed and listed "
        f"before any held out result was computed, and scored once at commit `{freeze['commit'][:7]}` (frozen {freeze['frozen_at'][:19].replace('T', ' ')} UTC).",
        f"- OBSERVED, regime change: tested degraded share was {before['share'].min():.3f} to {before['share'].max():.3f} on days up to "
        f"{before['day'].iloc[-1]} and {after['share'].min():.3f} to {after['share'].max():.3f} from {first_elev}. The median daily total of "
        f"en route aircraft counts over cell buckets (traffic units) fell from {before['units'].median():.0f} to {after['units'].median():.0f}. "
        f"The reduced traffic regime starts on {first_red} and the elevated degraded regime on {first_elev}; the development analysis "
        f"places the sharp change at about 2026-03-02. {n_red} of {n_days} study days ({n_held_red} of {n_held} held out days) are in "
        "the reduced traffic regime. No cause is identified and none is asserted.",
        "",
        f"Held out results ({n_held_norm} normal traffic days and {n_held_red} reduced traffic days). Intervals are day bootstrap intervals. "
        "The pooled column mixes two regimes and describes neither; read the regime columns.",
        "",
        "| Measure | Data class | Pooled | Traffic normal | Traffic reduced |",
        "|---|---|---|---|---|",
        *rows,
        "",
        "SYNTHETIC rows measure whether the detector finds scenarios that were injected into real traffic. They are not accuracy "
        "against real interference. Precision and detection delay are not measured on real data.",
        "",
        f"Preregistered predictions: {hits} HIT, {misses} MISS, {notev} not evaluable, out of {len(ev)} scored. Misses: {miss_ids}. "
        "Details in [docs/research/PREDICTIONS_RESULTS.md](docs/research/PREDICTIONS_RESULTS.md) and [docs/research/VALIDATION.md](docs/research/VALIDATION.md).",
        END,
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print("README.md has no STATUS markers", file=sys.stderr)
        return 2
    pre, rest = text.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    new = pre + build_block() + post
    if a.check:
        if new != text:
            print("README.md status block is out of date; run scripts/make_readme_status.py", file=sys.stderr)
            return 1
        return 0
    readme.write_text(new, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
