"""Generate docs/REPORT.md, the technical report, from result files.

  python scripts/make_report.py           # write docs/REPORT.md
  python scripts/make_report.py --check   # exit 1 if docs/REPORT.md differs from the generated text

Every number is read from results/headline.json, results/regimes.csv, results/predictions_scored.json, results/FREEZE.json,
results/dev and results/held_out files, and release/manifest.json. Prose around the numbers is fixed text; numbers in it
are formatted from the files above. The text avoids hyphenated words.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "REPORT.md"
CLS = {"synthetic": "SYNTHETIC", "observed": "OBSERVED"}


def _j(rel: str):
    return json.loads((ROOT / rel).read_text(encoding="utf-8"))


def _iv(r: dict) -> str:
    return f"{r['value']:.3f} ({r['ci_lo']:.3f} to {r['ci_hi']:.3f}; n {r['n']}, {r['n_days']} days)"


def build() -> str:
    sys.path.insert(0, str(ROOT / "src"))
    from tashwish.split import RULE_ID

    head = _j("results/headline.json")
    scored = _j("results/predictions_scored.json")
    freeze = _j("results/FREEZE.json")
    man = _j("release/manifest.json")
    reg = pd.read_csv(ROOT / "results/regimes.csv").sort_values("day")
    ev = pd.concat(
        [pd.read_csv(ROOT / f"results/{s}/observed_events.csv", keep_default_na=False) for s in ("dev", "held_out")]
    )
    rc = _j("results/dev/regime_check.json")
    cov = _j("results/held_out/observed_coverage_summary.json")
    done_at = (ROOT / "results/held_out/DONE").read_text(encoding="utf-8").strip()
    from tashwish.release.build import MIN_DEST_AIRCRAFT

    c = freeze["constants"]

    by = {(r["metric"], r["regime"]): r for r in head["results"]}
    cls = {r["metric"]: r["data_class"] for r in head["results"]}
    bases = [
        ("jamming_recall_easy", "Jamming like, easy tier, recall"),
        ("jamming_recall_medium", "Jamming like, medium tier, recall"),
        ("jamming_recall_hard", "Jamming like, hard tier, recall"),
        ("spoofing_recall_3plus_aircraft", "Spoofing like, 3 or more displaced aircraft, recall"),
        ("false_coverage_rate", "Covered cells with too few aircraft (false coverage)"),
    ]
    rows = []
    for k, label in bases:
        rows.append(
            f"| {label} | {CLS[cls[k]]} | {_iv(by[(k, 'pooled')])} | {_iv(by[(k + '_normal', 'traffic_normal')])} | "
            f"{_iv(by[(k + '_reduced', 'traffic_reduced')])} |"
        )

    sc = {r["id"]: r for r in scored if r.get("scored")}
    hits = sum(1 for r in sc.values() if r["hit"] is True)
    miss = [r for r in sc.values() if r["hit"] is False]
    notev = [r for r in sc.values() if r["hit"] is None]
    pred_rows = [f"| {r['id']} | {r['data_class']} | {r['claim']} | {r['short']} |" for r in miss + notev]

    days = man["days"]
    first_red = reg[reg["traffic"] == "reduced"]["day"].iloc[0]
    first_elev = reg[reg["degraded"] == "elevated"]["day"].iloc[0]
    dd = pd.DataFrame(days)
    pre = dd[dd["day"] < first_red]
    post = dd[dd["day"] >= first_elev]
    before = reg[reg["day"] < first_red]
    after = reg[reg["day"] >= first_elev]
    n_red = int((reg["traffic"] == "reduced").sum())

    n_ev = len(ev)
    n_unc = int((ev["label_uncertain"].astype(str) == "True").sum())
    kinds = ev["kind"].value_counts().to_dict()
    sp = ev[ev["kind"].isin(["spoofing_like", "both"])]
    n_sp = len(sp)
    n_min = int((sp["n_spoof_aircraft"].astype(float) == c["SPOOF_MIN_AIRCRAFT"]).sum())
    max_kt = float(pd.to_numeric(ev["median_implied_kt"], errors="coerce").max())

    s5 = sc.get("S5", {}).get("short", "n/a")
    j3 = sc.get("J3", {}).get("short", "n/a")
    j3t = next((r for r in scored if r["id"] == "J3t"), {}).get("short", "n/a")
    s1 = sc.get("S1", {}).get("short", "n/a")

    t = (
        f"""# Technical report: Tashwish, a Gulf GNSS interference observatory

Generated by `scripts/make_report.py` from result files. Nothing here is typed by hand: every number is read from
`results/headline.json`, `results/regimes.csv`, `results/predictions_scored.json`, `results/FREEZE.json`, the files in
`results/dev` and `results/held_out`, and `release/manifest.json`. Terms are explained in [GLOSSARY.md](GLOSSARY.md).

> Research and monitoring tool. Not for navigation or safety of life. No attribution of interference to any state or actor.
> No organisation has reviewed, endorsed or partnered with this project.

Data class labels: SYNTHETIC rows are tests on scenarios injected into real traffic and say nothing about accuracy against real
interference. OBSERVED rows are counts or rates on real days with nothing injected. MODEL rows check a property of the coverage
model or regime labels.

## 1. Question

Can public ADS-B broadcasts from commercial aircraft be turned into an open, auditable record of where and when aircraft in the
Gulf report degraded satellite navigation accuracy (jamming like) or implausible position jumps (spoofing like), with stated
uncertainty and with the cases where the method fails reported next to the cases where it works? The question is about
evidence of degraded position quality. It is not about who or what caused anything.

## 2. Data

- Source: adsb.lol `globe_history` daily archives (ODbL 1.0), reduced to the box {man["bbox"]["south"]:.0f} to {man["bbox"]["north"]:.0f} N and
  {man["bbox"]["west"]:.0f} to {man["bbox"]["east"]:.0f} E. Raw archives are not stored; only derived aggregates are released.
- Study window {man["study_window"]["start"]} to {man["study_window"]["end"]}, {len(days)} UTC days. Grid: H3 resolution {man["grid"]["h3_res"]}, {man["grid"]["bucket_hours"]} hour UTC buckets.
- Split rule `{RULE_ID}`: {len(freeze["dev_days"])} development days and {len(freeze["held_out_days"])} held out days, fixed by a hash of the date before any held out
  result existed. The held out run was executed once, at commit `{freeze["commit"][:7]}`, frozen {freeze["frozen_at"][:19].replace("T", " ")} UTC.
- Release candidate `{man["dataset_version"]}` (code commit `{man["code_commit"]}`), data class {man["data_class"]}.

## 3. Methods

Unique aircraft are counted per cell, bucket and altitude stratum. An aircraft is degraded when at least {c["DEGRADED_FRACTION"]} of its quality
bearing samples report NIC below {c["NIC_STRONG_BELOW"]} or NACp below {c["NACP_STRONG_BELOW"]}. A cell bucket is tested with at least {c["MIN_AIRCRAFT_PER_CELL"]} aircraft. A jamming like flag needs a
one sided binomial test against the cell's own baseline share, Benjamini and Yekutieli false discovery control at q {c["DETECT_FDR_Q"]}, at least {c["DETECT_MIN_BAD"]}
degraded aircraft and a Wilson lower bound of at least {c["DETECT_MIN_LOWER_BOUND"]}. A spoofing like event needs a jump of at least {c["SPOOF_JUMP_MIN_KT"]:.0f} kt and {c["SPOOF_JUMP_MIN_KM"]:.0f} km, more
than {c["SPOOF_JUMP_SPEED_RATIO"]} times the reported ground speed, clustered at the destination over at least {c["SPOOF_MIN_AIRCRAFT"]} distinct aircraft. A coverage model marks
cells the volunteer receiver network cannot see as insufficient data or coverage lost, never as quiet. Baselines and coverage are
fitted per regime on development days only. Full specification: [METHODOLOGY.md](METHODOLOGY.md).

Validation uses controlled injection of SYNTHETIC jamming and spoofing into real held out traffic, a coverage failure test, a
sensitivity study, and {len(sc)} preregistered predictions written before the held out run.

## 4. Results

Held out days, day bootstrap intervals (whole days resampled). The pooled column mixes two regimes and describes neither.

| Measure | Data class | Pooled | Traffic normal | Traffic reduced |
|---|---|---|---|---|
"""
        + "\n".join(rows)
        + f"""

Preregistered predictions: {hits} HIT, {len(miss)} MISS, {len(notev)} not evaluable, of {len(sc)} scored
([PREDICTIONS_RESULTS.md](PREDICTIONS_RESULTS.md)).

Real events (OBSERVED): {n_ev} events over {len(days)} days ({", ".join(f"{v} {k}" for k, v in sorted(kinds.items()))}); {n_unc} carry an
uncertain label. Of the {n_sp} spoofing like or both events, {n_min} involve only the minimum number of aircraft ({c["SPOOF_MIN_AIRCRAFT"]}).

Coverage model (MODEL, held out days): covered cells had enough aircraft {cov["covered"]["p_enough"]:.3f} of the time, no coverage cells
{cov["no_coverage"]["p_enough"]:.3f}. Details by regime are in the table above and in [VALIDATION.md](VALIDATION.md).

## 5. The regime finding (OBSERVED)

The data change sharply inside the window. Tested degraded share was {before["share"].min():.3f} to {before["share"].max():.3f} on days up to {before["day"].iloc[-1]} and
{after["share"].min():.3f} to {after["share"].max():.3f} from {first_elev}. The median number of aircraft seen per day (days before {first_red} versus days from {first_elev}) fell from {pre["aircraft"].median():,.0f} to {post["aircraft"].median():,.0f}, and the
median number of rows from {pre["rows"].median():,.0f} to {post["rows"].median():,.0f}. The reduced traffic regime starts on {first_red} and the elevated degraded regime on {first_elev}; {n_red} of {len(reg)}
study days are reduced traffic days. For the {rc["n_aircraft_in_both_periods"]} aircraft seen in both periods of the development days, the share of degraded samples was
{rc["same_aircraft_sample_share_early"]:.3f} early and {rc["same_aircraft_sample_share_late"]:.3f} late, so the rise is not only a different mix of aircraft.

No cause is identified and none is asserted. Possible readings include changes in the receiver network, in airspace use, in
airline fleets or schedules, and real interference; the data cannot separate them. The finding matters for method, not for
attribution: one baseline pooled across the change is wrong on both sides, so baselines and coverage are fitted per regime, and
results are reported per regime wherever they differ.

## 6. Where it fails

- Weak, small or short injected jamming is mostly missed. Hard tier recall pooled is {by[("jamming_recall_hard", "pooled")]["value"]:.3f}; criterion subset J3: {j3}; on testable scenarios: {j3t}.
- Jamming recall depends on the regime. Medium tier recall is {by[("jamming_recall_medium_normal", "traffic_normal")]["value"]:.3f} on normal traffic days and {by[("jamming_recall_medium_reduced", "traffic_reduced")]["value"]:.3f} on reduced traffic days.
- Spoofing like clusters of 3 or more aircraft: {s1}. Clusters of 1 or 2 aircraft: {s5}. Targeted spoofing of a single aircraft is
  out of reach of a crowd method by design.
- Coverage: false coverage is {by[("false_coverage_rate_normal", "traffic_normal")]["value"]:.3f} on normal days and {by[("false_coverage_rate_reduced", "traffic_reduced")]["value"]:.3f} on reduced days. After the regime change
  the receiver network no longer supports a coverage model fitted on earlier days as well.
- Real events are thin evidence: {n_min} of {n_sp} spoofing like or both events are the minimum 3 aircraft, {n_unc} of {n_ev} are uncertain, and the
  largest median implied speed in the event table is {max_kt:.0f} kt, which no aircraft flew, so a data error is a live explanation.
- The {len(miss)} missed predictions, and the {len(notev)} prediction that could not be evaluated as worded, with what was observed:

| ID | Data class | Prediction | Observed |
|---|---|---|---|
"""
        + "\n".join(pred_rows)
        + f"""

Caveats that apply to every held out number: the regime label of a day uses that day's own tested degraded share, which mutes events
on elevated days by construction; held out days interleave with development days inside a trending series and are not later in
time; days are not independent samples; precision and detection delay are not measured on real data.

## 7. Unverified items

- Whether the volume drop after {first_red} is a change in the receiver network, in traffic, or both. Not tested.
- Any cause of the rise in degraded reports. Not tested and not asserted.
- Whether any real event is interference. There is no ground truth in public ADS-B data. Replay of documented incident windows is
  weak evidence only.
- Behaviour on other seasons, other regions, or a longer window. Not tested.
- Continuous operation within the free tiers of GitHub Actions and Render: the documented limits are cited in
  [OPERATIONS.md](OPERATIONS.md); operation in practice is UNVERIFIED (see [NEXT_STEPS.md](NEXT_STEPS.md)).
- The legal reading of the ODbL for derived aggregates is conservative and is not legal advice ([LICENSING.md](LICENSING.md)).

## 8. Ethics and use

Tashwish is a research and monitoring tool. It must not be used for navigation, flight planning or any decision about the safety of
life. It does not attribute interference to any state or actor, and its text must not be read that way. Released files contain no
aircraft identifiers and no per point positions; event times are rounded to the bucket; events with fewer than {MIN_DEST_AIRCRAFT} aircraft omit
destination coordinates. A persistent emitter list used for scoring is keyed with a secret and is not published in clear.
Synthetic data is always labelled and kept apart from real data. No organisation has reviewed, endorsed or partnered with this
project, and no use by any entity is claimed.

## 9. Reproduction

`python scripts/make_report.py` regenerates this file. The held out run itself is single use (`results/held_out/DONE` exists,
completed {done_at}); the committed result files are its output.
"""
    )
    return t


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/REPORT.md is out of date; run scripts/make_report.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
